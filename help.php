		<section class="micro-section">
			<h2 style="color: #ffffff; font-size: 1.6em; font-weight: 300; margin-bottom: 0.5em;">Glossary</h2>
			<h3 style="color: #ffffff; font-weight: 700; font-size: 1.3em; margin-bottom: 1em;">What StraboSpot Terms Mean</h3>

			<ul style="list-style: none; padding-left: 0;">
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Attribute (Field):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A descriptive property of an observation (Spot), such as strike and dip, fold geometry, or shear zone thickness.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Downward Nest (Downward Nesting):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">The spatial containment of smaller or equal-sized Spots within a larger Spot. Used to associate detailed observations with a broader feature (e.g., measurements within a mapped structure).</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Edge (Relationship):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A defined connection between two Nodes (Spots) representing a logical or geological relationship (e.g., &ldquo;same bed&rdquo;). Edges may also include attributes (e.g., distance = 1 m).</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Group (Grouping):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A logical, conceptual, or classification-based association among multiple Spots.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Image:</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">Raster-based visual data, including photographs and sketches from device cameras or storage. Images cannot be altered within StraboSpot, but data may be overlaid on them.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Nest (Nesting):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A spatial relationship among Spots indicating shared location or hierarchical containment (e.g., features within a structure, or observations from a single outcrop).</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Node (Vertex):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A database entry representing an observation, measurement, sample, image, or related item. Nodes may initiate relationships or serve as parent Spots in nesting structures.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Purpose:</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">The documented intent behind a project, sample collection, or observation. May include detailed explanatory information.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Randy Style (Randolph Style):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A data collection approach in which a primary Spot is defined first, and multiple associated observations are recorded at the same location without unique spatial coordinates.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Sheet:</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">A user interface form for entering or managing specific types of data within StraboSpot (mobile or web).</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Spreadsheet:</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">The underlying data model or structured content framework supporting a Sheet.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Spot:</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">The fundamental data unit in StraboSpot (capital &ldquo;S&rdquo;). A spatially defined observation, measurement, image, sample, or relationship. All data entities are represented as Spots.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Tab:</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">The primary navigation element within the application interface, used to access different data types or functions.</span></li>
				<li style="margin-bottom: 1em;"><strong style="color: #ffffff;">Upward Nest (Upward Nesting):</strong><br>
					<span style="color: rgba(255, 255, 255, 0.85);">The aggregation of smaller Spots into a larger spatial interpretation (e.g., using multiple bedding measurements to define a fold orientation).</span></li>
			</ul>
